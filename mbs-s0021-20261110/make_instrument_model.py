#!/usr/bin/env python3
"""Build the mbs-0021 SAT beam instrument model.

One row per telescope, band and focal plane wafer slot (satp1 and satp3, f090
and f150, ws0 to ws6), each pointing at a custom beam table produced by
beams/convert_beams_to_mbs.py. The other bands and the LAT keep the Gaussian
beams of the mbs-s0016 instrument model and stay out of this table because
mapsims requires a beam file for every row of a table that has the beam_file
column.
"""
import argparse
import csv


def load_summary(path):
    with open(path) as handle:
        return list(csv.DictReader(handle))


def write_ipac(path, columns, types, units, rows):
    widths = []
    for name in columns:
        width = len(name) + 2
        for row in rows:
            width = max(width, len(str(row[name])) + 1)
        widths.append(width)

    def header_line(values):
        return "|" + "|".join(str(value).rjust(width - 1) for value, width in zip(values, widths)) + "|"

    def data_line(values):
        return "".join(str(value).rjust(width) for value, width in zip(values, widths))

    with open(path, "w") as handle:
        handle.write("\\ Text file in IPAC table format, read with astropy\n")
        handle.write("\\ mbs-0021 SAT f090 and f150 beams, one row per wafer slot\n")
        handle.write("\\ Generated by make_instrument_model.py, do not edit by hand\n")
        handle.write(header_line(columns) + "\n")
        handle.write(header_line(types) + "\n")
        handle.write(header_line(units) + "\n")
        handle.write(header_line(["null" for _ in columns]) + "\n")
        for row in rows:
            handle.write(data_line([row[name] for name in columns]) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--summary", default="beams/beam_summary.csv")
    parser.add_argument("--beams-dir", default="../beams")
    parser.add_argument("--output", default="instrument_model/instrument_model_sat_beams.tbl")
    args = parser.parse_args()

    summary = load_summary(args.summary)
    bands = {"f090": (92.0, 79.0, 105.0, "MF1"), "f150": (147.5, 130.0, 165.0, "MF2")}
    rows = []
    for entry in summary:
        center, low, high, mf = bands[entry["band"]]
        index = int(entry["ws"][2:])
        rows.append(
            {
                "telescope": entry["telescope"],
                "band": entry["band"],
                "fwhm": "%.1f" % float(entry["fwhm_arcmin"]),
                "center_frequency": "%.1f" % center,
                "low_frequency": "%.1f" % low,
                "high_frequency": "%.1f" % high,
                "nside": "4096",
                "car_resol": "4.0",
                "bandpass_file": "bandpass_sampler/SAT/resampled_bpasses_%s_w%d.tbl" % (mf, index),
                "beam_file": "%s/%s" % (args.beams_dir, entry["file"]),
            }
        )
    rows.sort(key=lambda row: (row["telescope"], row["band"], row["beam_file"]))
    columns = [
        "telescope",
        "band",
        "fwhm",
        "center_frequency",
        "low_frequency",
        "high_frequency",
        "nside",
        "car_resol",
        "bandpass_file",
        "beam_file",
    ]
    types = ["char", "char", "double", "double", "double", "double", "long", "double", "char", "char"]
    units = ["", "", "arcmin", "GHz", "GHz", "GHz", "", "arcmin", "", ""]
    write_ipac(args.output, columns, types, units, rows)
    print("wrote %s with %d rows" % (args.output, len(rows)))


if __name__ == "__main__":
    main()
